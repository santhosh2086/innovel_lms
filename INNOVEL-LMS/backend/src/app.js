import "dotenv/config";
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { pool, query } from './db.js';
import authRoutes from './routes/auth.js';
import signupRoutes from './routes/signup.js';
import courseRoutes from './routes/courses.js';
import userRoutes from './routes/users.js';
import studentRoutes from './routes/students.js';
import learningRoutes from './routes/learning.js';
import paymentRoutes from './routes/payments.js';
import assessmentRoutes from './routes/assessments.js';
import meetingRoutes from './routes/meetings.js';
import contentRoutes from './routes/content.js';
const app=express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin:(process.env.FRONTEND_URL||'http://localhost:5173').split(',').map(x=>x.trim()),credentials:true}));
app.use('/api/v1/payments/webhook',express.raw({type:'application/json',limit:'1mb'}));
app.use(express.json({limit:'1mb'}));
app.use(express.urlencoded({extended:false,limit:'1mb'}));
app.use('/api/v1/auth/login',rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:true,legacyHeaders:false}));
app.get('/api/v1/health',async(req,res)=>{try{await query('SELECT 1');res.json({ok:true,service:'innovel-lms-api',database:'connected'});}catch{res.status(503).json({ok:false,service:'innovel-lms-api',database:'unavailable'});}});
app.use('/api/v1/auth',authRoutes);
app.use('/api/v1/signup',signupRoutes);
app.use('/api/v1/courses',courseRoutes);
app.use('/api/v1/admin/users',userRoutes);
app.use('/api/v1/students',studentRoutes);
app.use('/api/v1',learningRoutes);
app.use('/api/v1/payments',paymentRoutes);
app.use('/api/v1',assessmentRoutes);
app.use('/api/v1',meetingRoutes);
app.use('/api/v1',contentRoutes);
app.get('/api/v1/admin/reports/summary', (await import('./middleware/auth.js')).requireAuth, (await import('./middleware/auth.js')).allowRoles('Admin'), async(req,res,next)=>{try{const r=await query(`SELECT (SELECT count(*) FROM users WHERE status='Active') AS active_users,(SELECT count(*) FROM courses) AS courses,(SELECT count(*) FROM enrollments WHERE status='Active') AS active_enrollments,(SELECT count(*) FROM payments WHERE status='Paid') AS paid_payments,(SELECT COALESCE(sum(amount),0) FROM payments WHERE status='Paid') AS paid_amount`);res.json({summary:r.rows[0]});}catch(e){next(e);}});
app.get('/api/v1/admin/audit', (await import('./middleware/auth.js')).requireAuth, (await import('./middleware/auth.js')).allowRoles('Admin'), async(req,res,next)=>{try{const r=await query('SELECT a.*,u.name AS actor_name,u.email AS actor_email FROM audit_logs a LEFT JOIN users u ON u.id=a.actor_id ORDER BY a.created_at DESC LIMIT 200');res.json({audit:r.rows});}catch(e){next(e);}});
app.use((req,res)=>res.status(404).json({error:{code:'NOT_FOUND',message:'API route not found.'}}));
app.use((err,req,res,next)=>{console.error('API error:',err.message);const status=err.status||500;res.status(status).json({error:{code:err.code||'INTERNAL_ERROR',message:status<500?err.message:'An unexpected server error occurred.'}});});
const port=Number(process.env.PORT||5000);
const server=app.listen(port,()=>console.log(`INNOVEL LMS API listening on port ${port}`));
const shutdown=async()=>{server.close(async()=>{await pool.end();process.exit(0);});};
process.on('SIGINT',shutdown);process.on('SIGTERM',shutdown);
